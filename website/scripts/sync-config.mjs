#!/usr/bin/env node
// Regenerates everything that derives from site.config.json. Runs before dev and build.
//   - wrangler.jsonc        (Worker name, /download worker + static assets, custom-domain route)
//   - public/site.webmanifest
//   - public/ favicons + og.png (only when their inputs changed; needs Edge/Chrome, warns if missing)
// Renaming the product = edit site.config.json, then npm run build.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadConfig } from './lib/site.mjs';
import { renderAssets } from './render-assets.mjs';

const cfg = loadConfig();

function writeIfChanged(rel, content) {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  if (fs.existsSync(p) && fs.readFileSync(p, 'utf8') === content) return false;
  fs.writeFileSync(p, content);
  console.log(`sync: wrote ${rel}`);
  return true;
}

// GitHub owner/name from the repo URL, for the /download worker.
const repoSlug = new URL(cfg.repo).pathname.replace(/^\/+|\/+$/g, '').replace(/\.git$/, '');

const wrangler = {
  name: `${cfg.slug}-site`,
  compatibility_date: '2026-10-01',
  // A tiny Worker runs first for /download only (302 to the latest release's .apk);
  // every other path is served straight from ./dist as static assets.
  main: './worker/index.js',
  assets: {
    directory: './dist',
    binding: 'ASSETS',
    not_found_handling: '404-page',
    html_handling: 'auto-trailing-slash',
    run_worker_first: ['/download', '/download/'],
  },
  vars: {
    GITHUB_REPO: repoSlug,
    // GitHub's API rejects requests without a User-Agent.
    USER_AGENT: `${cfg.slug}-site`,
  },
  // The sriharan.me zone must be on the same Cloudflare account.
  routes: [{ pattern: cfg.domain, custom_domain: true }],
};

writeIfChanged(
  'wrangler.jsonc',
  `// Generated by scripts/sync-config.mjs from site.config.json. Do not edit by hand.\n` +
    `// Deploy: npm run deploy  (build + wrangler deploy)\n` +
    JSON.stringify(wrangler, null, 2) +
    '\n',
);

writeIfChanged(
  'public/site.webmanifest',
  JSON.stringify(
    {
      name: cfg.name,
      short_name: cfg.name,
      description: cfg.description,
      start_url: '/',
      display: 'standalone',
      background_color: '#0B0B0A',
      theme_color: '#0B0B0A',
      icons: [
        { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
        { src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml' },
      ],
    },
    null,
    2,
  ) + '\n',
);

try {
  await renderAssets();
} catch (e) {
  const have = fs.existsSync(path.join(ROOT, 'public/og.png'));
  console.warn(
    `sync: could not render favicons/og.png (${String(e.message).split('\n')[0]}).` +
      (have ? ' Keeping the existing files.' : ' Run `npm run assets` on a machine with Edge or Chrome.'),
  );
}
